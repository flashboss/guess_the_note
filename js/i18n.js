const I18n = {
  locale: "en",

  t(key) {
    const table = I18N_STRINGS[this.locale] || I18N_STRINGS.en;
    return table[key] ?? I18N_STRINGS.en[key] ?? key;
  },

  detect() {
    try {
      const saved = localStorage.getItem("gtn-lang");
      if (saved && I18N_STRINGS[saved]) return saved;
    } catch (error) {
      /* private mode or TV storage may be unavailable */
    }
    const raw = String(navigator.language || "en").toLowerCase();
    if (raw.startsWith("zh")) return "zh";
    if (raw.startsWith("ja")) return "ja";
    const short = raw.slice(0, 2);
    return I18N_STRINGS[short] ? short : "en";
  },

  setLocale(locale) {
    this.locale = I18N_STRINGS[locale] ? locale : "en";
    try {
      localStorage.setItem("gtn-lang", this.locale);
    } catch (error) {
      /* ignore */
    }
  },

  apply() {
    document.documentElement.lang = this.locale;
    document.title = this.t("title");
    const meta = document.querySelector('meta[name="description"]');
    if (meta) meta.setAttribute("content", this.t("description"));

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = this.t(el.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", this.t(el.dataset.i18nAria));
    });
    document.querySelectorAll("[data-lang]").forEach((btn) => {
      btn.classList.toggle("is-active", btn.dataset.lang === this.locale);
      btn.setAttribute("aria-pressed", String(btn.dataset.lang === this.locale));
    });
    window.dispatchEvent(new Event("gtn:i18n"));
  },
};

I18n.setLocale(I18n.detect());
window.I18n = I18n;
